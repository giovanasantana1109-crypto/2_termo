-- TCL - TRANSAÇÕES E INTEGRIDADE REFERENCIAL
-- TRANSAÇÃO RESOLVE PROBLEMAS DE PROCEDIMENTO, MAS NÃO RESOLVE PROBLEMAS DE INTEGRIDADE REFERWNCIAL
-- SEM TRANSAÇÃO: PARTE PODE PERMANECER GRAVADA
-- COM TRANSAÇÃO: PODE CONFIRMAR TUDO OU DESFAZER TUDO

-- CONCEITOS INICIAS
-- TRANSAÇÃO É UM CONJUNTO DE OPERAÇÕES
START TRANSACTION;
INSERT ...
UPDATE ...
INSERT ...
SELECT ...
COMMIT ...

-- SEQUENCIA
-- INICIO - OPRACOES - VALIDAÇÃO - COMMIT - ROLLBACK

-- EX1 : CONFIRMA AS ALTERAÇÕES DENTRO DA TRANSAÇÃO
START TRANSACTION;
UPDATE produto
SET PRECO = 8.50
WHERE ID_PRODUTO = 1;
COMMIT

SELECT* FROM PRODUTO;

-- EX2: ROOLBACK - DESFAZ AS ALTERAÇÕES AINDA NÃO CONFIRMADAS
START TRANSACTION;
UPDATE produto
SET PRECO = 16.50
WHERE ID_PRODUTO = 2;

ROLLBACK;
SELECT * FROM PRODUTO;

-- EX3: SAVEPOINT - CRIAR UMPONTO PARA REGISTRAR UMA ETAPA DA TRANSAÇÃO
START TRANSACTION;
UPDATE produto
SET PRECO = PRECO * 1.05
WHERE ID_CATEGORIA = 1;

SAVEPOINT REAJUSTE_CAFES;

UPDATE produto
SET PRECO = PRECO * 1.50
WHERE ID_CATEGORIA = 1;

ROLLBACK TO SAVEPOINT REAJUSTE_CAFES;

COMMIT;

SELECT * FROM PRODUTO;

-- EX4: REMOVE O SAVEPOINT
RELEASE SAVEPOINT REAJUSTE_CAFES;

-- TRANSAÇÃP NÃO SUBSTITUI CONSTRAINT
-- TRANSACÃO : CONSTROLA SE UM CONJUNTO DE OPERAÇÕES SERÁ CONFIRMADO OU DESFEITO
-- CONSTRAINT ; IMPEDE QUE DETERMINADOS ESTADOS INVÁLIDOS SEJAM ACEITOS

-- EX5: ATULIZAR ESTOQUE COM VALORES NEGADOS
