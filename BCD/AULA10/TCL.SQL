-- EX 7 : ON DELET
-- RESTRIC : BLOQUEIA EXCLUSÃO COM DEPENTES
-- CASCADE : EXCLUI DEPENDENTES
-- SET NULL : REMONE REFERÊNCIA

CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES PEDIDO (ID_PEDIDO) ON DELETE CASCADE;
-- CASCADE NÃO É A MELHOR OPÇÃO POIS ELE EXCLUI CLIENTE E TODOS OS PEDIDO RELACIONADOS E APAGA UM HISTORIA CRIANDO

-- EX8: EXCLUSÃO FÍSICA E LÓGICA
