-- OBS:

-- ESTRUTURA DE NORMALIZAÇÃO 1FN
-- FOI IDENTIFICADO NOS GRUPOD REPETIDOS COMO PRODUTO1, PRODUTO2 E PRODUTO3
-- A 1FN FAZ SENTIDO POR QUE UM PEDIDO PODE POSSUIR QUALQUER QUANTIDADE SEM CRIAR NOVAS COLUNAS
-- FOI GERADO AS TABELAS PEDIDO E ITEM_PEDIDO PARA ESSA NORMALIZAÇÃO

-- ESTRUTURA DE NORMALIÇão 2FN
-- OS DADOS DO CLIENTE NÃO PERTENCEM AO PEDIDO. ELES DESCREVEM O CLIENTE . O NOME DA CATEGORIA TAMBEM NÃO DEVE SER REPETIDO EM CASA PRODUTO
-- SEPARAÇÃO DAS TABELAS CLIENTE, PRODUTO E CATEGORIA QUE INVLVE CHAVES PRIMARIAS OU CHAVE COMPOSTAS
--  EM UMA CHAVE COMPOSTA OS ATRINUTOS COMUNS DEVEM DEPENDER DA CHAVE PRIMARIA OU INTEIRA

-- ESTRUTURA DE NORMALIZAÇÃO 3FN 
-- NOME_CATEGORIA QUE DEPENDE DO ID_CATEGORIA PORTANTO DEVE ESTAR EM UMA TABELA 
-- UTILIZAM DEPENDENCIAS OU CRIAM DEPENDECIAS

-- RESUMO: 1FN RESOLVE GRUPOS REPETITIVOS; 2FN REMOVE DEPENDENCIAS PARCIAIS DE CHAVES COMPOSTAS; 3FN REMOVE DEPENDENCAIS INCEVIDAS ENTRE ATRIBUTOS NÃO-CHAVE PRIMARIAS

