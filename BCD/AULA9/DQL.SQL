-- PARTE 2 - RELACIONAMENTOS ENTRE TABELAS - JOINS
-- JOIN - JUNÇÃO DE TABELAS
-- EX 19: PEDIDDO COM NOME DO CLIENTE
-- INNER JOIN - RETONA REGISTROS QUE POSSUEM CORRESPONDêNCIAS ENTRE TABELAS

SELECT P.ID_PEDIDO, P.DATA_PEDIDO, C.NOME AS CLIENTES , P.VALOR_TOTAL
FROM PEDIDO AS P 
INNER JOIN CLIENTE AS C 
ON C.ID_CLIENTE = P.ID_CLIENTE;

-- OBS: RELACIONE O CLIENTE CUJO ID_CLIENTE É IGUAL AP ID_CLIENTE GRAVADO NO PEDIDO
-- P E C SÃO APELIDOS OU ALIASES PARA DEIXAR MAIS CURTAS E LEGÍVEIS

-- LEFT JOIN - MANTÉM TODOS OS REGISTROS DA TABELA DE ESQUERDA MESMO QUANDO NÃO POSSUI CORRESPONDêNCIA NA TABELA DA DIREITA
-- EX20: TODOS OS CLIENTES, INCLUSIVE QUEM NUNCA COMPROU OU QUEM NUNCA REALIZOU PEDIDO

SELECT C.NOME, P.ID_PEDIDO, P.DATA_PEDIDO
FROM CLIENTE AS C 
LEFT JOIN PEDIDO AS P 
ON P.ID_CLIENTE = C.ID_CLIENTE
ORDER BY C.NOME;

